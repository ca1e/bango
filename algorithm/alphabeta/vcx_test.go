// TestKillSearchVCTPerfSanity: the block-three addition widens the defender's
// branch — VCT must still finish a threat-dense position comfortably inside
// its quarter-budget slice. The diagram has fours and threes for both sides
// but no forced win (defender holds counter-fours).
func TestKillSearchVCTPerfSanity(t *testing.T) {
	if testing.Short() {
		t.Skip("timing-sensitive")
	}
	s := diagramToSearcher(t, `
.........
.........
..x.oo...
...xoo...
..x.oo...
...x.....
.........
.........
.........
`)
	start := time.Now()
	r := s.runKillSearch(2 * time.Second)
	elapsed := time.Since(start)
	t.Logf("kill search on mixed-threat board: move=%d, elapsed=%v", r, elapsed)
	// generous ceiling: a quarter-budget probe on a dense 9x9 board must
	// resolve in well under a second, not approach its deadline
	if elapsed > 800*time.Millisecond {
		t.Fatalf("VCT too slow after widening the defence set: %v", elapsed)
	}
}

