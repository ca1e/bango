// TestKillSearchVCFChain: attacker can build four-after-forced-block.
// Shape (9x9, o to move):
//
//	row4: . . . o o . .   → play (2,4) makes .ooo o? no—
//
// We use a textbook double-threat: o at (3,4),(4,4) plus (4,3),(3,5)diag…
// simplest verifiable chain: open three; opponent has no fours, so VCT finds
// live-four → win in 3 attacker moves.
func TestKillSearchVCTOpenThree(t *testing.T) {
	s := diagramToSearcher(t, `
.........
.........
.........
.........
.........
.........
.........
...ooo...
.........
`)
	r := s.runKillSearch(3 * time.Second)
	if r < 0 {
		t.Fatal("kill search missed a forced win from an open three")
	}
	x, y := r%9, r/9
	// the winning start is one of the live-four-making extensions or the gap
	if y != 7 || (x != 1 && x != 2 && x != 6 && x != 7) {
		t.Fatalf("kill move = (%d,%d), want an extension of the three on row 7", x, y)
	}
}

