// TestKillSearchFindsVCF: with a double open three (a proven forced win via
// live fours), the kill search must report it. The shape gives o two crossing
// open threes; any defence still leaves a live-four → five.
func TestKillSearchFindsVCF(t *testing.T) {
	s := diagramToSearcher(t, `
.........
.........
.........
.........
.........
.........
...o.o...
...o.o...
....x....
`)
	r := s.runKillSearch(2 * time.Second)
	if r < 0 {
		t.Fatal("kill search missed a double-three forced win")
	}
	x, y := r%9, r/9
	// every winning start is on one of the two threes
	if !((y == 6 || y == 7) && (x == 2 || x == 3 || x == 5 || x == 7)) {
		t.Fatalf("kill move = (%d,%d), want a point on the threes", x, y)
	}
}

