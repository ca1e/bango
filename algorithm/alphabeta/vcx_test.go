// TestKillSearchVCFThroughForcedBlock: a sound kill that goes THROUGH the
// defender's forced block must still be found: rush four (block forced) →
// live four from the second three (block forced) → five.
func TestKillSearchVCFThroughForcedBlock(t *testing.T) {
	// row 4: x o o o .  → (6,4) rush four, block (7,4) forced
	// col 5: o (5,4) o (5,5) o (5,6) — live three, live-four makers (5,3)/(5,7)
	s := diagramToSearcher(t, `
.........
.........
.........
.........
..xooo...
......o..
......o..
.........
.........
`)
	r := s.runKillSearch(2 * time.Second)
	if r < 0 {
		t.Fatal("kill search lost the forced-block VCF chain")
	}
	x, y := r%9, r/9
	// (6,4) is the plain rush four, (7,4) the jump four (ooo.o) — both force
	// the block at (6,4) and then win through the column-5 live three
	if y != 4 || (x != 6 && x != 7) {
		t.Fatalf("kill move = (%d,%d), want a four-maker on row 4 ((6,4)/(7,4))", x, y)
	}
}

